using System;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;
using TextEdit = Robust.Client.UserInterface.Controls.TextEdit;

namespace Content.Client._Solreign.Library.UI;

/// <summary>
///     The Station Archive submission window body: a title field, a multi-line body field (the
///     existing Paper writing UI's <c>TextEdit</c> control, the <c>PaperWindow</c> idiom), and a
///     submit button. Stateless — no server-pushed UI state, since this BUI never displays anything
///     but the form itself; the outcome of a submit arrives as a private popup (server-side).
///     Client-side clamping here is UX only; the server re-sanitizes and re-caps both fields
///     regardless (see <c>LibraryRules</c>).
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class SolreignLibrarySubmitWindow : FancyWindow
{
    /// <summary>Mirrors <c>LibraryRules.MaxTitleLength</c> (Content.Server) — UX convenience only, never the authority.</summary>
    public const int MaxTitleLength = 100;

    /// <summary>Mirrors <c>LibraryRules.MaxBodyLength</c> (Content.Server) — UX convenience only, never the authority.</summary>
    public const int MaxBodyLength = 6000;

    public event Action<string, string>? OnWorkSubmitted;

    public SolreignLibrarySubmitWindow()
    {
        RobustXamlLoader.Load(this);

        TitleInput.OnTextChanged += _ =>
        {
            if (TitleInput.Text.Length > MaxTitleLength)
                TitleInput.Text = TitleInput.Text[..MaxTitleLength];

            UpdateSubmitEnabled();
        };
        BodyInput.OnTextChanged += _ =>
        {
            UpdateCharCount();
            UpdateSubmitEnabled();
        };
        SubmitButton.OnPressed += _ => TrySubmit();

        UpdateCharCount();
        UpdateSubmitEnabled();
    }

    private void TrySubmit()
    {
        var title = TitleInput.Text.Trim();
        var body = Rope.Collapse(BodyInput.TextRope).Trim();
        if (title.Length == 0 || body.Length == 0)
            return;

        if (title.Length > MaxTitleLength)
            title = title[..MaxTitleLength];
        if (body.Length > MaxBodyLength)
            body = body[..MaxBodyLength];

        OnWorkSubmitted?.Invoke(title, body);

        TitleInput.Text = string.Empty;
        BodyInput.TextRope = Rope.Leaf.Empty;
        BodyInput.CursorPosition = new TextEdit.CursorPos();
        UpdateCharCount();
        UpdateSubmitEnabled();
    }

    private void UpdateCharCount()
    {
        CharCountLabel.Text = Loc.GetString("solreign-library-ui-char-count",
            ("current", BodyInput.TextLength), ("max", MaxBodyLength));
    }

    private void UpdateSubmitEnabled()
    {
        SubmitButton.Disabled = TitleInput.Text.Trim().Length == 0 || BodyInput.TextLength == 0;
    }
}
